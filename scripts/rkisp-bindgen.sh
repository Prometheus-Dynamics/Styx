#!/usr/bin/env bash
# Regenerates crates/rkisp/src/uapi/isp3x.rs from the Rockchip ISP3 uAPI headers in
# crates/rkisp/headers (rockchip-linux/kernel develop-5.10 include/uapi/linux; their own include
# of rk-camera-module.h is cut). Needs bindgen-cli and clang.
set -euo pipefail
cd "$(dirname "$0")/.."
inc="$(mktemp -d)"
trap 'rm -rf "$inc"' EXIT
mkdir -p "$inc/linux"
for h in crates/rkisp/headers/*.h; do
    sed '/#include <linux\/rk-camera-module.h>/d' "$h" >"$inc/linux/$(basename "$h")"
done
out=crates/rkisp/src/uapi/isp3x.rs
{
    echo '//! @generated by bindgen from `headers/rk-isp3-config.h` (and the `rk-isp21`/`rk-isp2`'
    echo '//! headers it includes), Rockchip kernel `develop-5.10`, licensed'
    echo '//! `(GPL-2.0+ WITH Linux-syscall-note) OR MIT`; used here under MIT. Regenerate with'
    echo '//! `scripts/rkisp-bindgen.sh`; do not edit.'
    echo
    echo '#![allow(non_camel_case_types, non_upper_case_globals, dead_code, clippy::all)]'
    echo
    bindgen "$inc/linux/rk-isp3-config.h" --use-core --no-layout-tests --no-doc-comments \
        --allowlist-type 'isp3x_.*|rkisp3x_.*' \
        --allowlist-var 'ISP3X_.*|ISP2X_RAWAE.*|ISP2X_RAWHIST.*|ISP2X_HIST.*' \
        -- -I "$inc" -target aarch64-linux-gnu | sed '1d'
} >"$out"
rustfmt --edition 2024 "$out"

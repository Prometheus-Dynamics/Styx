/// Chroma QP for luma QP 30 to 51 (below 30 they are equal).
const CHROMA_QP_HIGH: [u8; 22] = [
    29, 30, 31, 32, 32, 33, 34, 34, 35, 35, 36, 36, 37, 37, 37, 38, 38, 38, 39, 39, 39, 39,
];

/// The chroma QP for luma QP `qp` (no `chroma_qp_index_offset`).
pub(super) fn chroma_qp(qp: u8) -> u8 {
    if qp < 30 {
        qp
    } else {
        CHROMA_QP_HIGH[usize::from(qp - 30)]
    }
}

/// The class (both even, both odd, mixed) of raster position `i` in a 4x4 block.
pub(super) const fn pos_class(i: usize) -> usize {
    let (x, y) = (i & 3, i >> 2);
    match (x & 1, y & 1) {
        (0, 0) => 0,
        (1, 1) => 1,
        _ => 2,
    }
}

/// The luma and chroma tables at `quality` (1–100), scaled as libjpeg does: 50 is Annex K
/// as it is, 100 all ones; every entry 1–255 (baseline).
pub(super) fn quant_tables(quality: u8) -> [[u16; 64]; 2] {
    let q = u32::from(quality.clamp(1, 100));
    let scale = if q < 50 { 5000 / q } else { 200 - 2 * q };
    let scaled =
        |base: &[u8; 64]| base.map(|b| ((u32::from(b) * scale + 50) / 100).clamp(1, 255) as u16);
    [scaled(&LUMA_QUANT), scaled(&CHROMA_QUANT)]
}


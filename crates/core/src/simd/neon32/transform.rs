//! 8x8 tile transposes in 32-bit Arm NEON assembly (see [`crate::simd::TransposeTile`]).
//! Generated register ladders: each loads the tile's rows, transposes in registers, optionally
//! reverses each output row, and stores the rows `dst_stride` apart.

use core::arch::asm;

/// 8x8 bytes: the classic `vtrn.8` / `.16` / `.32` ladder leaves column k in d<k>.
///
/// # Safety
/// The CPU must have NEON; 8 rows of 8 pixels readable at `src_stride` and writable at
/// `dst_stride` (see [`crate::simd::scalar::transpose_tile`]).
pub(in crate::simd) unsafe fn transpose_tile_u8(
    src: *const u8,
    src_stride: usize,
    dst: *mut u8,
    dst_stride: isize,
    reverse: bool,
) {
    // SAFETY: per the contract above.
    unsafe {
        asm!(
            ".fpu neon",
            "vld1.8 {{d0}}, [{s}], {ss}",
            "vld1.8 {{d1}}, [{s}], {ss}",
            "vld1.8 {{d2}}, [{s}], {ss}",
            "vld1.8 {{d3}}, [{s}], {ss}",
            "vld1.8 {{d4}}, [{s}], {ss}",
            "vld1.8 {{d5}}, [{s}], {ss}",
            "vld1.8 {{d6}}, [{s}], {ss}",
            "vld1.8 {{d7}}, [{s}], {ss}",
            "vtrn.8 d0, d1",
            "vtrn.8 d2, d3",
            "vtrn.8 d4, d5",
            "vtrn.8 d6, d7",
            "vtrn.16 d0, d2",
            "vtrn.16 d1, d3",
            "vtrn.16 d4, d6",
            "vtrn.16 d5, d7",
            "vtrn.32 d0, d4",
            "vtrn.32 d1, d5",
            "vtrn.32 d2, d6",
            "vtrn.32 d3, d7",
            "cmp {rev}, #0",
            "beq 3f",
            "vrev64.8 d0, d0",
            "vrev64.8 d1, d1",
            "vrev64.8 d2, d2",
            "vrev64.8 d3, d3",
            "vrev64.8 d4, d4",
            "vrev64.8 d5, d5",
            "vrev64.8 d6, d6",
            "vrev64.8 d7, d7",
            "3:",
            "vst1.8 {{d0}}, [{d}], {ds}",
            "vst1.8 {{d1}}, [{d}], {ds}",
            "vst1.8 {{d2}}, [{d}], {ds}",
            "vst1.8 {{d3}}, [{d}], {ds}",
            "vst1.8 {{d4}}, [{d}], {ds}",
            "vst1.8 {{d5}}, [{d}], {ds}",
            "vst1.8 {{d6}}, [{d}], {ds}",
            "vst1.8 {{d7}}, [{d}], {ds}",
            s = inout(reg) src => _,
            ss = in(reg) src_stride,
            d = inout(reg) dst => _,
            ds = in(reg) dst_stride,
            rev = in(reg) u32::from(reverse),
            out("d0") _, out("d1") _, out("d2") _, out("d3") _, out("d4") _, out("d5") _, out("d6") _, out("d7") _,
            options(nostack),
        );
    }
}

/// 8x8 3-byte pixels: `vld3` splits the channels, each transposed as bytes (channel c of
/// row r in d<3r+c>).
///
/// # Safety
/// The CPU must have NEON; 8 rows of 8 pixels readable at `src_stride` and writable at
/// `dst_stride` (see [`crate::simd::scalar::transpose_tile`]).
pub(in crate::simd) unsafe fn transpose_tile_rgb(
    src: *const u8,
    src_stride: usize,
    dst: *mut u8,
    dst_stride: isize,
    reverse: bool,
) {
    // SAFETY: per the contract above.
    unsafe {
        asm!(
            ".fpu neon",
            "vld3.8 {{d0, d1, d2}}, [{s}], {ss}",
            "vld3.8 {{d3, d4, d5}}, [{s}], {ss}",
            "vld3.8 {{d6, d7, d8}}, [{s}], {ss}",
            "vld3.8 {{d9, d10, d11}}, [{s}], {ss}",
            "vld3.8 {{d12, d13, d14}}, [{s}], {ss}",
            "vld3.8 {{d15, d16, d17}}, [{s}], {ss}",
            "vld3.8 {{d18, d19, d20}}, [{s}], {ss}",
            "vld3.8 {{d21, d22, d23}}, [{s}], {ss}",
            "vtrn.8 d0, d3",
            "vtrn.8 d6, d9",
            "vtrn.8 d12, d15",
            "vtrn.8 d18, d21",
            "vtrn.16 d0, d6",
            "vtrn.16 d3, d9",
            "vtrn.16 d12, d18",
            "vtrn.16 d15, d21",
            "vtrn.32 d0, d12",
            "vtrn.32 d3, d15",
            "vtrn.32 d6, d18",
            "vtrn.32 d9, d21",
            "vtrn.8 d1, d4",
            "vtrn.8 d7, d10",
            "vtrn.8 d13, d16",
            "vtrn.8 d19, d22",
            "vtrn.16 d1, d7",
            "vtrn.16 d4, d10",
            "vtrn.16 d13, d19",
            "vtrn.16 d16, d22",
            "vtrn.32 d1, d13",
            "vtrn.32 d4, d16",
            "vtrn.32 d7, d19",
            "vtrn.32 d10, d22",
            "vtrn.8 d2, d5",
            "vtrn.8 d8, d11",
            "vtrn.8 d14, d17",
            "vtrn.8 d20, d23",
            "vtrn.16 d2, d8",
            "vtrn.16 d5, d11",
            "vtrn.16 d14, d20",
            "vtrn.16 d17, d23",
            "vtrn.32 d2, d14",
            "vtrn.32 d5, d17",
            "vtrn.32 d8, d20",
            "vtrn.32 d11, d23",
            "cmp {rev}, #0",
            "beq 3f",
            "vrev64.8 d0, d0",
            "vrev64.8 d1, d1",
            "vrev64.8 d2, d2",
            "vrev64.8 d3, d3",
            "vrev64.8 d4, d4",
            "vrev64.8 d5, d5",
            "vrev64.8 d6, d6",
            "vrev64.8 d7, d7",
            "vrev64.8 d8, d8",
            "vrev64.8 d9, d9",
            "vrev64.8 d10, d10",
            "vrev64.8 d11, d11",
            "vrev64.8 d12, d12",
            "vrev64.8 d13, d13",
            "vrev64.8 d14, d14",
            "vrev64.8 d15, d15",
            "vrev64.8 d16, d16",
            "vrev64.8 d17, d17",
            "vrev64.8 d18, d18",
            "vrev64.8 d19, d19",
            "vrev64.8 d20, d20",
            "vrev64.8 d21, d21",
            "vrev64.8 d22, d22",
            "vrev64.8 d23, d23",
            "3:",
            "vst3.8 {{d0, d1, d2}}, [{d}], {ds}",
            "vst3.8 {{d3, d4, d5}}, [{d}], {ds}",
            "vst3.8 {{d6, d7, d8}}, [{d}], {ds}",
            "vst3.8 {{d9, d10, d11}}, [{d}], {ds}",
            "vst3.8 {{d12, d13, d14}}, [{d}], {ds}",
            "vst3.8 {{d15, d16, d17}}, [{d}], {ds}",
            "vst3.8 {{d18, d19, d20}}, [{d}], {ds}",
            "vst3.8 {{d21, d22, d23}}, [{d}], {ds}",
            s = inout(reg) src => _,
            ss = in(reg) src_stride,
            d = inout(reg) dst => _,
            ds = in(reg) dst_stride,
            rev = in(reg) u32::from(reverse),
            out("d0") _, out("d1") _, out("d2") _, out("d3") _, out("d4") _, out("d5") _, out("d6") _, out("d7") _, out("d8") _, out("d9") _, out("d10") _, out("d11") _, out("d12") _, out("d13") _, out("d14") _, out("d15") _, out("d16") _, out("d17") _, out("d18") _, out("d19") _, out("d20") _, out("d21") _, out("d22") _, out("d23") _,
            options(nostack),
        );
    }
}

/// 8x8 2-byte pixels, one row a q register: 4x4 transposes in each half, then the halves
/// exchanged across the row pairs (k, k + 4).
///
/// # Safety
/// The CPU must have NEON; 8 rows of 8 pixels readable at `src_stride` and writable at
/// `dst_stride` (see [`crate::simd::scalar::transpose_tile`]).
pub(in crate::simd) unsafe fn transpose_tile_u16(
    src: *const u8,
    src_stride: usize,
    dst: *mut u8,
    dst_stride: isize,
    reverse: bool,
) {
    // SAFETY: per the contract above.
    unsafe {
        asm!(
            ".fpu neon",
            "vld1.16 {{d0, d1}}, [{s}], {ss}",
            "vld1.16 {{d2, d3}}, [{s}], {ss}",
            "vld1.16 {{d4, d5}}, [{s}], {ss}",
            "vld1.16 {{d6, d7}}, [{s}], {ss}",
            "vld1.16 {{d8, d9}}, [{s}], {ss}",
            "vld1.16 {{d10, d11}}, [{s}], {ss}",
            "vld1.16 {{d12, d13}}, [{s}], {ss}",
            "vld1.16 {{d14, d15}}, [{s}], {ss}",
            "vtrn.16 q0, q1",
            "vtrn.16 q2, q3",
            "vtrn.16 q4, q5",
            "vtrn.16 q6, q7",
            "vtrn.32 q0, q2",
            "vtrn.32 q1, q3",
            "vtrn.32 q4, q6",
            "vtrn.32 q5, q7",
            "vswp d1, d8",
            "vswp d3, d10",
            "vswp d5, d12",
            "vswp d7, d14",
            "cmp {rev}, #0",
            "beq 3f",
            "vrev64.16 q0, q0",
            "vswp d0, d1",
            "vrev64.16 q1, q1",
            "vswp d2, d3",
            "vrev64.16 q2, q2",
            "vswp d4, d5",
            "vrev64.16 q3, q3",
            "vswp d6, d7",
            "vrev64.16 q4, q4",
            "vswp d8, d9",
            "vrev64.16 q5, q5",
            "vswp d10, d11",
            "vrev64.16 q6, q6",
            "vswp d12, d13",
            "vrev64.16 q7, q7",
            "vswp d14, d15",
            "3:",
            "vst1.16 {{d0, d1}}, [{d}], {ds}",
            "vst1.16 {{d2, d3}}, [{d}], {ds}",
            "vst1.16 {{d4, d5}}, [{d}], {ds}",
            "vst1.16 {{d6, d7}}, [{d}], {ds}",
            "vst1.16 {{d8, d9}}, [{d}], {ds}",
            "vst1.16 {{d10, d11}}, [{d}], {ds}",
            "vst1.16 {{d12, d13}}, [{d}], {ds}",
            "vst1.16 {{d14, d15}}, [{d}], {ds}",
            s = inout(reg) src => _,
            ss = in(reg) src_stride,
            d = inout(reg) dst => _,
            ds = in(reg) dst_stride,
            rev = in(reg) u32::from(reverse),
            out("d0") _, out("d1") _, out("d2") _, out("d3") _, out("d4") _, out("d5") _, out("d6") _, out("d7") _, out("d8") _, out("d9") _, out("d10") _, out("d11") _, out("d12") _, out("d13") _, out("d14") _, out("d15") _,
            options(nostack),
        );
    }
}

/// 8x8 4-byte pixels, one row two q registers: the four 4x4 blocks transposed in place
/// (`vtrn.32` and a half exchange), output row k joining the blocks' column k; reversed, the
/// halves swap order and each reverses.
///
/// # Safety
/// The CPU must have NEON; 8 rows of 8 pixels readable at `src_stride` and writable at
/// `dst_stride` (see [`crate::simd::scalar::transpose_tile`]).
pub(in crate::simd) unsafe fn transpose_tile_u32(
    src: *const u8,
    src_stride: usize,
    dst: *mut u8,
    dst_stride: isize,
    reverse: bool,
) {
    // SAFETY: per the contract above.
    unsafe {
        asm!(
            ".fpu neon",
            "vld1.32 {{d0, d1, d2, d3}}, [{s}], {ss}",
            "vld1.32 {{d4, d5, d6, d7}}, [{s}], {ss}",
            "vld1.32 {{d8, d9, d10, d11}}, [{s}], {ss}",
            "vld1.32 {{d12, d13, d14, d15}}, [{s}], {ss}",
            "vld1.32 {{d16, d17, d18, d19}}, [{s}], {ss}",
            "vld1.32 {{d20, d21, d22, d23}}, [{s}], {ss}",
            "vld1.32 {{d24, d25, d26, d27}}, [{s}], {ss}",
            "vld1.32 {{d28, d29, d30, d31}}, [{s}], {ss}",
            "vtrn.32 q0, q2",
            "vtrn.32 q4, q6",
            "vswp d1, d8",
            "vswp d5, d12",
            "vtrn.32 q1, q3",
            "vtrn.32 q5, q7",
            "vswp d3, d10",
            "vswp d7, d14",
            "vtrn.32 q8, q10",
            "vtrn.32 q12, q14",
            "vswp d17, d24",
            "vswp d21, d28",
            "vtrn.32 q9, q11",
            "vtrn.32 q13, q15",
            "vswp d19, d26",
            "vswp d23, d30",
            "cmp {rev}, #0",
            "bne 3f",
            "vst1.32 {{d0, d1}}, [{d}]!",
            "vst1.32 {{d16, d17}}, [{d}], {ds16}",
            "vst1.32 {{d4, d5}}, [{d}]!",
            "vst1.32 {{d20, d21}}, [{d}], {ds16}",
            "vst1.32 {{d8, d9}}, [{d}]!",
            "vst1.32 {{d24, d25}}, [{d}], {ds16}",
            "vst1.32 {{d12, d13}}, [{d}]!",
            "vst1.32 {{d28, d29}}, [{d}], {ds16}",
            "vst1.32 {{d2, d3}}, [{d}]!",
            "vst1.32 {{d18, d19}}, [{d}], {ds16}",
            "vst1.32 {{d6, d7}}, [{d}]!",
            "vst1.32 {{d22, d23}}, [{d}], {ds16}",
            "vst1.32 {{d10, d11}}, [{d}]!",
            "vst1.32 {{d26, d27}}, [{d}], {ds16}",
            "vst1.32 {{d14, d15}}, [{d}]!",
            "vst1.32 {{d30, d31}}, [{d}], {ds16}",
            "b 4f",
            "3:",
            "vrev64.32 q0, q0",
            "vswp d0, d1",
            "vrev64.32 q1, q1",
            "vswp d2, d3",
            "vrev64.32 q2, q2",
            "vswp d4, d5",
            "vrev64.32 q3, q3",
            "vswp d6, d7",
            "vrev64.32 q4, q4",
            "vswp d8, d9",
            "vrev64.32 q5, q5",
            "vswp d10, d11",
            "vrev64.32 q6, q6",
            "vswp d12, d13",
            "vrev64.32 q7, q7",
            "vswp d14, d15",
            "vrev64.32 q8, q8",
            "vswp d16, d17",
            "vrev64.32 q9, q9",
            "vswp d18, d19",
            "vrev64.32 q10, q10",
            "vswp d20, d21",
            "vrev64.32 q11, q11",
            "vswp d22, d23",
            "vrev64.32 q12, q12",
            "vswp d24, d25",
            "vrev64.32 q13, q13",
            "vswp d26, d27",
            "vrev64.32 q14, q14",
            "vswp d28, d29",
            "vrev64.32 q15, q15",
            "vswp d30, d31",
            "vst1.32 {{d16, d17}}, [{d}]!",
            "vst1.32 {{d0, d1}}, [{d}], {ds16}",
            "vst1.32 {{d20, d21}}, [{d}]!",
            "vst1.32 {{d4, d5}}, [{d}], {ds16}",
            "vst1.32 {{d24, d25}}, [{d}]!",
            "vst1.32 {{d8, d9}}, [{d}], {ds16}",
            "vst1.32 {{d28, d29}}, [{d}]!",
            "vst1.32 {{d12, d13}}, [{d}], {ds16}",
            "vst1.32 {{d18, d19}}, [{d}]!",
            "vst1.32 {{d2, d3}}, [{d}], {ds16}",
            "vst1.32 {{d22, d23}}, [{d}]!",
            "vst1.32 {{d6, d7}}, [{d}], {ds16}",
            "vst1.32 {{d26, d27}}, [{d}]!",
            "vst1.32 {{d10, d11}}, [{d}], {ds16}",
            "vst1.32 {{d30, d31}}, [{d}]!",
            "vst1.32 {{d14, d15}}, [{d}], {ds16}",
            "4:",
            s = inout(reg) src => _,
            ss = in(reg) src_stride,
            d = inout(reg) dst => _,
            ds16 = in(reg) dst_stride - 16,
            rev = in(reg) u32::from(reverse),
            out("d0") _, out("d1") _, out("d2") _, out("d3") _, out("d4") _, out("d5") _, out("d6") _, out("d7") _, out("d8") _, out("d9") _, out("d10") _, out("d11") _, out("d12") _, out("d13") _, out("d14") _, out("d15") _, out("d16") _, out("d17") _, out("d18") _, out("d19") _, out("d20") _, out("d21") _, out("d22") _, out("d23") _, out("d24") _, out("d25") _, out("d26") _, out("d27") _, out("d28") _, out("d29") _, out("d30") _, out("d31") _,
            options(nostack),
        );
    }
}
